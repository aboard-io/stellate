/** dB a record is trimmed by: the share `PULL` of its distance from TARGET,
 *  railed. A row nobody measured answers 0. */
export function trimDb(gk) {
  /* A ROW IS `[loudest second, peak]` — two numbers, because the ceiling is a
     question about the peak and the target is a question about the level. A
     bare number is still read (that was the first table's shape) and simply
     has no headroom argument to make. */
  const row = MEASURED[gk];
  if (row == null) return 0;
  const m = Array.isArray(row) ? row[0] : row;
  const pk = Array.isArray(row) ? row[1] : null;
  if (!isFinite(m)) return 0;
  const want = (TARGET - m) * PULL;
  if (want <= 0) return want < FLOOR ? FLOOR : +want.toFixed(2);
  const room = (pk != null && pk > 0)
    ? 20 * Math.log10(PEAK_MAX / pk) : LIFT_MAX;
  const ceil = Math.min(LIFT_MAX, Math.max(0, room));
  return +(want > ceil ? ceil : want).toFixed(2);
}

/** the same number as a gain. 1 for every unmeasured row. */
export function trimOf(gk) {
  const d = trimDb(gk);
  return d ? Math.pow(10, d / 20) : 1;
}

/**
 * Scale one bar's units by the record's trim, the way audio/desk.js scales
 * them by the master fader — and for the same measured reason:
 *   · a SAMPLED voice and a DRUM read `lvl` (sampler note gain, state-engine
 *     `sets.level = u.lvl * amp`);
 *   · a MODELLED voice's level was baked into `params.level` and `gmul` at cast
 *     time and the desk moves neither, so its contribution is scaled on the
 *     three sends instead — all of them, never some, or the balance moves.
 * Returns the SAME ARRAY when the trim is 1, so an unmeasured record allocates
 * nothing and renders byte for byte as it did.
 */
export function levelled(units, gk) {
  const g = trimOf(gk);
  if (g === 1 || !units || typeof units !== "object") return units;
  /* THE UNITS ARE A MAP, NOT A LIST, and the first build of this file assumed
     a list — `Array.isArray` was false, the guard returned the argument, and a
     record trimmed by 7.95 dB rendered at exactly the level it started at.
     Measured before this line: house -14.4 dB with the trim in the table and
     -14.4 without it. audio/plan.js hands `{ v0: {...}, drums: {...} }`, which
     is how every other reader of a bar plan walks it (test/_odpress.cjs:
     `Object.entries((p0 && p0.units) || {})`). Both shapes are handled now
     because a shape assumption is what this paragraph is about. */
  const scale = (u) => {
    if (!u || typeof u !== "object") return u;
    const isDrum = !!u.drum || !!(u.__meta && u.__meta.drum);
    const v = { ...u };
    if (u.sampler || isDrum) {
      if (v.lvl != null) v.lvl = v.lvl * g;
    } else {
      v.dry = (v.dry != null ? v.dry : 1) * g;
      if (v.rev) v.rev = v.rev * g;
      if (v.del) v.del = v.del * g;
      if (v.genre) v.genre = v.genre * g;
    }
    return v;
  };
  if (Array.isArray(units)) return units.map(scale);
  const out = {};
  /* THE `__`-PREFIXED KEYS ARE NOT UNITS — the bar plan carries its own
     bookkeeping in the same object (test/_odpress.cjs skips exactly these), and
     scaling one would be scaling a number that is not a level. */
  for (const k of Object.keys(units))
    out[k] = k.slice(0, 2) === "__" ? units[k] : scale(units[k]);
  return out;
}
