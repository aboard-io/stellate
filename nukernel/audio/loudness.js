// nukernel/audio/loudness.js — EVERY RECORD ARRIVES AT ROUGHLY THE SAME
// LOUDNESS, and the number that makes it so is measured rather than typed.
//
// Paul, 2026-09-08: *"Can you watch levels on genres? Everything you added
// recently is super loud. Do a pass through all of the genres. Like salsa is
// unlistenably loud. Should be totally possible to automate this."*
//
// WHAT THE PASS FOUND, and it is the reason this file is a TABLE and not a
// law. `tools/levels.js` presses every record's busiest section and reads the
// loudest second; across the catalogue that number runs from about -14 dB to
// about -51, a spread of 16 dB between the fifth and ninety-fifth percentiles
// and 37 between the extremes. The obvious single causes were tested against
// the measurements and NONE of them explains it: the correlation with the
// number of seated voices is -0.13, with the kit's lane count 0.26, with the
// row's own `tone.gain` 0.28, with tempo 0.06. A record's level is emergent —
// the samples' own recorded levels, the density of the writing, how much of
// the bar the drums fill, which sends are open — so there is no summing law to
// fix and no constant to divide by. What there is, is a MEASUREMENT.
//
// SO IT IS REPLAYGAIN, FOR A CATALOGUE THAT GENERATES ITSELF. One number per
// row, `TRIM[gk]` in dB, generated by `node tools/levels.js --write` and read
// here. Nothing else in the tree may write it: a hand-typed trim is a number
// nobody can re-derive after the engine moves, and the engine moves weekly.
//
// IT IS NOT FULL NORMALISATION, ON PURPOSE. A string quartet SHOULD be quieter
// than a house record — that difference is music, and flattening every row onto
// one number would take the dynamics of the whole catalogue out. What is being
// removed is the ACCIDENT: `PULL` is the share of each row's distance from the
// target that the trim actually takes back, so a record 12 dB hot comes down 9
// and keeps 3 of its own loudness. The rails are asymmetric for a reason a
// meter gives: pulling down is free, and pushing up spends HEADROOM.
//
// AND THE LIFT IS CAPPED BY THE HEADROOM ITSELF, NOT BY A CONSTANT. The first
// build railed every lift at +6 dB, and measured on the trimmed render that
// rail was the thing standing between the quiet end of the catalogue and the
// target: `polychoral` came up 6.0 dB and was still 14 under, `counterpoint`
// 5.9 and still 4 under. It is also a rail those records did not need — their
// peaks are 0.02 and 0.03, which is 30 dB of unused headroom. So the ceiling
// is computed per row from the peak the pass measured: a record may be lifted
// until its loudest sample would reach `PEAK_MAX`, and no further. A row with
// a hot peak keeps its transient; a row recorded into nothing gets its level.
// `LIFT_MAX` stands over that as a sanity rail — a 30 dB lift is not a mix
// decision, it is a bug in the row, and it should be found rather than hidden.
//
// AND THE TRIM RIDES THE ROUTE, WHICH IS THE MASTER FADER'S OWN PATH
// (audio/desk.js: "IT LANDS ON THE ROUTE, not on `level`"). A sampled voice and
// a drum read `lvl`; a modelled voice's level was baked at cast time and reads
// only its sends — so both are scaled, dry and wet together at one gain, all
// three sends and never some. That is a fader, and this is a fader.
