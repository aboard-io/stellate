/* ---------- pitch, per window, on a single saw --------------------------
   AUTOCORRELATION and not a spectral peak, for erhu.test.js E7's reason: the
   claim is where the FUNDAMENTAL is at each instant, and a filtered saw's
   tallest bin is not reliably its first partial. The probe voice is set to
   ONE oscillator with no detune and no octave layer (see `probeSet`), so the
   lag is unambiguous. */
function pitchAt(buf, from, n, loHz, hiHz) {
  let e = 0; for (let i = 0; i < n; i++) { const v = buf[from + i] || 0; e += v * v; }
  if (Math.sqrt(e / n) < 1e-4) return 0;
  const lo = Math.max(2, Math.floor(SR / hiHz)), hi = Math.min(n - 2, Math.ceil(SR / loHz));
  const cor = new Float64Array(hi + 1);
  let best = -Infinity;
  for (let lag = lo; lag <= hi; lag++) {
    let s = 0;
    for (let i = 0; i + lag < n; i++) s += (buf[from + i] || 0) * (buf[from + i + lag] || 0);
    cor[lag] = s / (n - lag);
    if (cor[lag] > best) best = cor[lag];
  }
  // THE SMALLEST LAG THAT IS NEARLY AS GOOD, not the tallest peak. A periodic
  // signal correlates just as well at twice its period, and the tallest bin
  // flips between the two mid-glide — measured, the 450 ms walk read
  // 437 437 219 219 219 441, which is one note reported as two octaves. The
  // 90% rule is the standard octave guard and it is why this is not a spectral
  // peak either (see erhu.test.js E7).
  for (let lag = lo; lag <= hi; lag++) if (cor[lag] >= 0.9 * best) return SR / lag;
  return 0;
}
const traj = (buf, t0, t1, step, lo, hi) => {
  const n = Math.floor(SR * 0.030), out = [];
  for (let t = t0; t < t1 - 0.030; t += step)
    out.push([+t.toFixed(3), +pitchAt(buf, Math.floor(t * SR), n, lo, hi).toFixed(1)]);
  return out;
};

/* ---------- the module, driven by hand ----------------------------------- */
let _gen = null;
async function gen() {
  if (!_gen) {
    const { FaustMonoDspGenerator } = await import(
      path.join(FAUST, "node_modules/@grame/faustwasm/dist/esm/index.js"));
    _gen = new FaustMonoDspGenerator();
  }
  return _gen;
}
async function distFactory(name) {
  const code = fs.readFileSync(path.join(FAUST, "dist", name + "-module.wasm"));
  return { cfactory: 0, code: new Uint8Array(code), module: await WebAssembly.compile(code),
           json: fs.readFileSync(path.join(FAUST, "dist", name + "-meta.json"), "utf8"), poly: false };
}
let _compiler = null;
async function compiler() {
  if (!_compiler) {
    const { instantiateFaustModuleFromFile, LibFaust, FaustCompiler } = await import(
      path.join(FAUST, "node_modules/@grame/faustwasm/dist/esm/index.js"));
    // faustwasm picks its loader off `typeof window` — and this file stubs a
    // window for nukernel's own modules, which sends libfaust down the BROWSER
    // path and makes it `fetch` an absolute filesystem path. Hidden for the one
    // call that reads the compiler off disk, and put straight back.
    const w = globalThis.window; delete globalThis.window;
    let mod;
    try {
      mod = await instantiateFaustModuleFromFile(
        path.join(FAUST, "node_modules/@grame/faustwasm/libfaust-wasm/libfaust-wasm.js"));
    } finally { globalThis.window = w; }
    _compiler = new FaustCompiler(new LibFaust(mod));
    const libDir = path.join(FAUST, "dsp");
    for (const f of fs.readdirSync(libDir).filter((x) => x.endsWith(".lib")).sort())
      _compiler.fs().writeFile(f, fs.readFileSync(path.join(libDir, f), "utf8"));
  }
  return _compiler;
}
/** the module as it was BEFORE the slider: the takeover undone, compiled here. */
async function preGlideFactory(name) {
  const src = fs.readFileSync(path.join(FAUST, "dsp", name + ".dsp"), "utf8")
    .replace(/ : gsmooth;/, " : si.smoo;");
  const d = await (await gen()).compile(await compiler(), name + "_pre", src, "-ftz 2");
  if (!d || !d.factory) throw new Error("reference compile failed for " + name);
  return d.factory;
}
/** two notes, ONE instance, gate held across the change (the legato case). */
async function twoNotes(factory, root, sets, f1, f2, secA, secB) {
  const proc = await (await gen()).createOfflineProcessor(SR, BS, factory);
  const meta = JSON.parse(factory.json), book = {};
  (function walk(items) { for (const it of items || []) it.items ? walk(it.items)
    : (book[it.label.trim().split(/\s/)[0]] = it.address); })(meta.ui);
  const set = (k, v) => { if (book[k] != null) proc.setParamValue(book[k], v); };
  for (const [k, v] of Object.entries(sets)) set(k, v);
  set("gain", 1);
  const nA = Math.floor(SR * secA), T = Math.floor(SR * (secA + secB));
  const out = new Float32Array(T);
  set("freq", f1); set("gate", 1);
  for (let s = 0; s < T; s += BS) {
    if (s <= nA && s + BS > nA) set("freq", f2);
    const len = Math.min(BS, T - s);
    out.set((await proc.render([], len))[0].subarray(0, len), s);
  }
  return out;
}
