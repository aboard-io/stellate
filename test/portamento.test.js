/* ================= G3 · the trajectory, at the module ===================== */
console.log("G3 — the pitch between two notes: step, ramp, and the accident in between");
{
  const F = await distFactory("supersaw");
  const A = 220, B = 440, T0 = 0.5;
  const runs = {};
  for (const g of [0, 1, 250])
    runs[g] = await twoNotes(F, "supersaw", { ...probeSet, glide: g }, A, B, T0, 0.7);
  const at = (buf, ms) => pitchAt(buf, Math.floor((T0 + ms / 1000) * SR),
                                  Math.floor(SR * 0.030), 170, 520);
  // glide 1 — a SNAP. Within 30 ms the whole measuring window is the new note.
  ok(Math.abs(at(runs[1], 40) - B) < 12, "glide 1 ms SNAPS — 440 Hz 40 ms after the change",
     at(runs[1], 40).toFixed(1) + " Hz");
  // glide 250 — still travelling where the snap has long since arrived. The
  // comparison is against the SNAP at the same instant, not against the nominal
  // 440: an autocorrelation lag is quantised (the 90% rule reads a settled 440
  // as ~450), and a gate that compares a measurement to a number it did not
  // measure is measuring its own estimator.
  const mid = at(runs[250], 100), snap = at(runs[1], 100);
  ok(mid > A + 20 && mid < snap - 15,
     "glide 250 ms is still BETWEEN the notes 100 ms in, where the snap has arrived — a ramp, not a step",
     mid.toFixed(1) + " Hz against the snap's " + snap.toFixed(1) + " Hz");
  ok(Math.abs(at(runs[250], 400) - snap) < 0.02 * snap, "…and has arrived by 400 ms",
     at(runs[250], 400).toFixed(1) + " Hz");
  // monotone: a portamento only ever goes one way
  const walk = traj(runs[250], T0, T0 + 0.45, 0.02, 170, 520).map((r) => r[1]);
  let backwards = 0;
  for (let i = 1; i < walk.length; i++) if (walk[i] < walk[i - 1] - 8) backwards++;
  ok(backwards === 0, "the whole 450 ms walk is monotone upward — no wobble, no overshoot",
     walk.map((x) => x.toFixed(0)).join(" → "));
  // glide 0 — THE ACCIDENT, named. si.smoo is a fixed 0.999 pole (~96 ms).
  const zero = at(runs[0], 40);
  ok(zero > A + 20 && zero < B - 5,
     "glide 0 is NOT a step — it is the module's own si.smoo, and that is the pitch bend Paul hears",
     zero.toFixed(1) + " Hz 40 ms in, arriving " + at(runs[0], 200).toFixed(1) + " Hz at 200 ms");
}

/* ================= G4 · through the whole bridge, to the air ============== */
console.log("G4 — a row's `tone.glide` in SECONDS reaches the samples");
{
  const plan = (glide) => ({
    bpm: 60, seed: 3, kit: "tr909",
    bars: [{ barSteps: 16, ev: [{ kind: "line", v: 0, n: 57, off: 0, dur: 16, vel: 6 }] },
           { barSteps: 16, ev: [{ kind: "line", v: 0, n: 69, off: 0, dur: 16, vel: 6 }] }],
    reverb: 0, delay: { beats: 0.75, feedback: 0 },
    seat: () => ({ chair: "line",
      synth: { dsp: "supersaw", level: 0.5, set: { ...probeSet, ...(glide != null ? { glide } : {}) } } }),
    bass: null,
  });
  const TE = await import(R("nukernel/audio/to-engine.js"));
  const render = async (p) => {
    const t = TE.toEngine(p, { SE, K, E });
    for (const u of Object.values(t.units)) if (u.inserts) u.inserts = [];
    const sched = SE.mapEvents(E, t.state, t.ev, { units: t.units });
    const spb = sched.spb, totalSec = sched.totalBeats * spb;
    const { L } = await PRESS.assemble(t.state, sched,
      { mkProc: PRESS.mkProc, rootOf: PRESS.rootOf, buffers: {}, speech: null,
        dx7Presets: PRESS.loadDx7Presets() },
      { spb, totalSec, TOTAL: Math.ceil(totalSec * SR) });
    return { L, units: t.units, ev: t.ev };
  };
  // the recipe door, in seconds, exactly as a row writes it
  const u = SE.pitchedUnit("melody", { model: "stack", glideSec: 0.25 }, { bpm: 120, seed: 1 });
  ok(u.params.glide === 250, "`tone.glide: 0.25` becomes the module's own 250 ms",
     "params.glide = " + u.params.glide);
  // 220 Hz for a bar, then 440 for a bar, at 60 bpm — one second a beat, so the
  // second note lands at t = 4 s and there is a whole bar of it to read.
  const dry = await render(plan(1)), wet = await render(plan(300));
  const bar = 4;
  const at = (r, ms) => pitchAt(r.L, Math.floor((bar + ms / 1000) * SR),
                                Math.floor(SR * 0.030), 170, 520);
  ok(wet.units.v0.params.glide === 300 && dry.units.v0.params.glide === 1,
     "the chair's unit carries the glide the seat asked for",
     "wet " + wet.units.v0.params.glide + " ms, control " + dry.units.v0.params.glide + " ms");
  ok(at(wet, 120) > 240 && at(wet, 120) < at(dry, 120) - 15,
     "120 ms into the second note the 300 ms chair is STILL CLIMBING and the snapping one has arrived",
     at(wet, 120).toFixed(1) + " Hz against the control's " + at(dry, 120).toFixed(1) + " Hz");
  const walk = traj(wet.L, bar, bar + 0.5, 0.05, 170, 520).map((r) => r[1]);
  ok(walk[0] < walk[walk.length - 1] - 40,
     "…and the whole half-second reads as a climb, on the tape's own render path",
     walk.map((x) => x.toFixed(0)).join(" → "));
}

