/* ===== F · THE TRANSFORMS ARE THE INVOLUTIONS THEY CLAIM TO BE =========== *
 * Property-tested over seeded random rows, both shapes the module accepts:
 * bare numbers, and {p, d} objects whose durations the augmentation scales.
 * The classical operations are algebra before they are music, and algebra
 * that only holds for the row somebody happened to try is not algebra.      */
{
  const rng = seeded(0xBACCA11);
  const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);
  const rows = [];
  for (let n = 0; n < 200; n++) {
    const len = 1 + Math.floor(rng() * 12);
    const obj = rng() < 0.5;
    const row = [];
    for (let i = 0; i < len; i++) {
      const p = 36 + Math.floor(rng() * 48);
      row.push(obj ? { p, d: 1 + Math.floor(rng() * 8) } : p);
    }
    rows.push(row);
  }
  const bad = { retro: [], inv: [], invAxis: [], dur: [], rot: [], ri: [], tr: [] };
  for (const row of rows) {
    const axis = 30 + Math.floor(rng() * 60);
    if (!eq(T.retrograde(T.retrograde(row)), row)) bad.retro.push(row);
    if (!eq(T.invert(T.invert(row, axis), axis), row)) bad.inv.push(row);
    if (!eq(T.invert(T.invert(row)), row)) bad.invAxis.push(row);
    if (!eq(T.diminish(T.augment(row, 2), 2), row)) bad.dur.push(row);
    if (!eq(T.rotate(row, row.length), row)) bad.rot.push(row);
    if (!eq(T.rotate(row, -row.length), row)) bad.rot.push(row);
    if (!eq(T.retrogradeInversion(row, axis), T.retrograde(T.invert(row, axis))))
      bad.ri.push(row);
    if (!eq(T.transpose(T.transpose(row, 7), -7), row)) bad.tr.push(row);
  }
  const say = (k, what) => ok(!bad[k].length, "F · " + what + " (" + rows.length +
    " seeded rows)", JSON.stringify(bad[k][0] || "").slice(0, 160));
  say("retro", "retrograde is its own inverse");
  say("inv", "inversion about a named axis is its own inverse");
  say("invAxis", "and so is inversion about the row's own first note");
  say("dur", "diminish undoes augment: diminish(augment(x, 2), 2) === x");
  say("rot", "rotating by the row's length, either way, is the identity");
  say("ri", "retrograde-inversion IS inversion followed by retrograde");
  say("tr", "transposition by n and by -n cancel");
  // and the operations are not silently mutating what they were handed
  const one = [{ p: 60, d: 2 }, { p: 62, d: 1 }];
  const before = JSON.stringify(one);
  T.retrograde(one); T.invert(one, 60); T.augment(one, 3); T.rotate(one, 1);
  T.sequence(one, 2, 3); T.transpose(one, 5);
  ok(JSON.stringify(one) === before,
     "F · and none of them mutates the row it was handed");
}

/* ===== G · EVERY RULE BITES, AND EVERY RULE STAYS QUIET ================== *
 * For each of theory.js's rule codes: a minimal score that violates exactly
 * that rule (asserted reported) and a minimal score that does not (asserted
 * silent). This is the gate that stops a rule from becoming a no-op — the
 * failure a move from tools/chorale-check.js invites and that no clean run of
 * the committed chorale would ever show, because a rule that never fires
 * makes a clean score cleaner.
 *
 * ALLRULES drives the loop, so a rule added to theory.js without a case here
 * FAILS rather than passing unnoticed.                                      */
{
  const V = (...ns) => ns.map((notes, i) => ({ name: "v" + (i + 1), notes }));
  const CH = (pcs, thirdPc) => ({ chords: [{ pcs, thirdPc }] });
  const CASES = {
    // a soprano under its own floor; the same soprano on the floor
    range: [{ voices: [{ name: "s", lo: 60, hi: 79, notes: [59] }], opts: {} },
            { voices: [{ name: "s", lo: 60, hi: 79, notes: [60] }], opts: {} }],
    // the declared order IS the definition: v1 below v2
    crossing: [{ voices: V([60], [62]), opts: {} },
               { voices: V([62], [60]), opts: {} }],
    // more than an octave between two UPPER voices (the lowest pair is exempt)
    spacing: [{ voices: V([80], [60], [50]), opts: {} },
              { voices: V([72], [60], [50]), opts: {} }],
    nonchord: [{ voices: V([61]), opts: CH([0, 4, 7], 4) },
               { voices: V([60]), opts: CH([0, 4, 7], 4) }],
    nothird: [{ voices: V([60], [67]), opts: CH([0, 4, 7], 4) },
              { voices: V([60], [64]), opts: CH([0, 4, 7], 4) }],
    doubledLT: [{ voices: V([71], [59]), opts: { leadingTone: 11 } },
                { voices: V([71], [60]), opts: { leadingTone: 11 } }],
    // both voices move, same direction, a perfect fifth on both sides
    parallel5: [{ voices: V([60, 62], [53, 55]), opts: {} },
                { voices: V([60, 62], [53, 51]), opts: {} }],
    parallel8: [{ voices: V([60, 62], [48, 50]), opts: {} },
                { voices: V([60, 62], [48, 47]), opts: {} }],
    // outer voices, similar motion into a perfect interval, top voice LEAPING
    direct: [{ voices: V([60, 67], [48, 60]), opts: {} },
             { voices: V([60, 62], [48, 55]), opts: {} }],
    leap: [{ voices: V([60, 73]), opts: {} },
           { voices: V([60, 72]), opts: {} }],
    // three semitones is a minor third until the caller says which pair of
    // pitch classes is the augmented second — here Eb to F# in G minor
    aug2: [{ voices: V([63, 66]), opts: { aug2Pair: [3, 6] } },
           { voices: V([60, 63]), opts: { aug2Pair: [3, 6] } }],
    ltResolve: [{ voices: V([71, 69]), opts: { leadingTone: 11, tonic: 0 } },
                { voices: V([71, 72]), opts: { leadingTone: 11, tonic: 0 } }],
  };
  const missing = T.ALLRULES.filter((r) => !CASES[r]);
  ok(!missing.length,
     "G · every rule theory.js declares has a bite-and-quiet case here",
     missing.join(" "));
  const noBite = [], noQuiet = [];
  for (const code of T.ALLRULES) {
    const c = CASES[code];
    if (!c) continue;
    const bite = T.faults(c[0].voices, { ...c[0].opts, rules: [code] });
    const quiet = T.faults(c[1].voices, { ...c[1].opts, rules: [code] });
    if (!bite.length || !bite.every((f) => f.code === code)) noBite.push(code);
    if (quiet.length) noQuiet.push(code + " (" + quiet.map((f) => f.text).join("; ") + ")");
  }
  ok(!noBite.length,
     "G · all " + T.ALLRULES.length + " rules BITE on a score built to break " +
     "exactly that rule", noBite.join(" "));
  ok(!noQuiet.length,
     "G · and all " + T.ALLRULES.length + " STAY QUIET on a score that does not",
     noQuiet.join("\n       "));
}

