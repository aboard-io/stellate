#!/usr/bin/env node
/* gen-sitemap.js — THE SITEMAP for the box at stellate.app: one URL per
   record, and every one of them plays.
   ==========================================================================
   WHAT IT MAKES. nukernel/sitemap.xml — the site root, and then one deep link
   per row in the catalogue that can actually be addressed by a link.

   WHY THIS IS NOT A DATA EXPORT. The sitemap the old star-map app shipped
   carried a HAND-PICKED crate of twenty-two links, one exemplar per family,
   with a comment saying that dumping all 274 anchors "would be a data export,
   not a sitemap". That was the right call for that site, where the catalogue
   was one input to a map and the map was the page. It is the wrong call for
   this one. Here the catalogue IS the site: there is exactly one page, and
   every distinct thing a person can arrive at is a (place, year) pair. A
   sitemap that named twenty-two of them would be hiding 478 real destinations
   from the only reader a sitemap has. So the rule is the opposite one — EVERY
   ROW THAT OPENS GETS A LINE — and the honest limits are the protocol's own
   (50,000 URLs, 50 MB uncompressed), which 500 rows is nowhere near.

   THE LINKS ARE THE FEED'S LINKS. Same builder, same grammar, same seed rule:
   this file requires tools/build/gen-feed.js for `linkFor` and reads nothing
   about the share format for itself. Two files spelling one URL grammar is two
   spellings to drift, and the whole point of a sitemap entry and a feed entry
   agreeing is that a search result and a subscription land on the same music.
   The grammar and the argument for it are documented at length in the header
   of gen-feed.js; the short version is:

       https://stellate.app/?at=<place>&y=<year>&s=<seed>&t=band

   — read by `readLink()` in nukernel/ui/eight.js and spent by `open()` in
   nukernel/ui/atlas.js, which resolves (place, year) to the nearest record.
   The place and the year are the row's own `label` ("Kingston 1969") split by
   nukernel/atlas.js's own label regex, so no place and no year is invented
   here; the seed is a stable hash of the genre key, so the URL is the same
   music today, next year, and in whatever cache a crawler keeps.

   WHAT IS SKIPPED, AND WHY. Ten rows carry a name instead of a "Place Year"
   label — `silence`, `dance`, `guitarrock`, `pop`, `simple`, `solo`, `vocal`,
   `backing`, `riff`, `pad`. These are not records of a music from a place at a
   time; they are the box's own utility rows (a blank record to build on, the
   plain-noun starting points), and nukernel/atlas.js EXCLUDEs every one of
   them from the globe for exactly that reason. There is no (place, year) that
   names them, so there is no link to give a crawler, so they are not here. A
   row is also skipped if its place is not on the globe or if another row
   shares its place AND year — in both cases the page would open something
   other than the row we named, and a sitemap full of URLs that open the wrong
   thing is worse than a shorter sitemap. gen-feed.js's `addressable()` asks
   the app's own resolver, per row, on every build.

   A FRAGMENT IN A SITEMAP, SAID OUT LOUD. Crawlers have historically ignored
   everything after the `#`, so 500 lines that differ only in their fragment
   may be indexed as one URL. That is a known cost and it is taken on purpose:
   this app's share grammar IS a fragment (the box is one page and the record
   is client-side state), the alternative is to invent a query-string grammar
   the app does not read, and a sitemap that lies about what the URLs are would
   be worse than one a crawler collapses. The file therefore does the one
   useful thing it can: it is a complete, honest, machine-readable index of
   every record this box holds, and the header comment says what the links are
   so a person reading the raw XML knows too.

   NO <lastmod>. It would have to come from the clock or from the git log, and
   both make the bytes move when nothing about the catalogue changed. The
   output is DERIVED and gitignored, regenerated by the deploy, and running
   this twice produces identical bytes — which is the property that lets the
   deploy rsync it without churning.

   USAGE
     node tools/build/gen-sitemap.js         # write nukernel/sitemap.xml
     node tools/build/gen-sitemap.js --dry   # print the summary, write nothing
   Exits non-zero if the catalogue yields no links or the XML fails its check.
   Zero dependencies, no network. */

"use strict";
const fs = require("fs");
const path = require("path");
const FEED = require("./gen-feed.js");

const ROOT = path.resolve(__dirname, "..", "..");
const OUT = path.join(ROOT, "nukernel", "sitemap.xml");
const SITE = FEED.SITE;
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;")
  .replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/* THE ORDER IS THE CATALOGUE'S, NOT THE ALPHABET'S. `nukernel/genres.js` keeps
   its rows in the order the box itself lists them, and a sitemap that reordered
   them would make a diff every time a row moved for an unrelated reason. */
function build() {
  const rows = FEED.LINKABLE.map((gk) => FEED.linkFor(gk)).filter(Boolean);
  if (!rows.length) throw new Error("the catalogue yielded no addressable rows");

  const x = [];
  x.push('<?xml version="1.0" encoding="UTF-8"?>');
  x.push("<!-- sitemap.xml — STELLATE. DERIVED: written by tools/build/gen-sitemap.js");
  x.push("     at deploy time, never by hand, never committed.");
  x.push("");
  x.push("     One page and " + rows.length + " records. This box is a single HTML page whose");
  x.push("     content is a catalogue of " + Object.keys(FEED.GENRES).length + " genres, each one a piece of music from a");
  x.push("     place at a time — Kingston 1969, Vienna 1788, Ugarit 1400 BC. Every URL");
  x.push("     below opens one of them and plays it:");
  x.push("");
  x.push("         " + SITE + "/?at=<place>&amp;y=<year>&amp;s=<seed>&amp;t=band");
  x.push("");
  x.push("     `at` and `y` name the record — the place and the year are the row's own");
  x.push("     label, so nothing here is invented — and `s` is a seed fixed per record,");
  x.push("     which is what makes the URL always the same music rather than a fresh");
  x.push("     reading each visit. A BC year is a negative number (y=-1400). The same");
  x.push("     links appear in the release feeds (" + SITE + "/feed.xml), built by the");
  x.push("     same code: tools/build/gen-feed.js linkFor().");
  x.push("");
  x.push("     WHY A QUERY AND NOT THE FRAGMENT THE APP WRITES. A crawler does not");
  x.push("     read fragments: with `#` every line below would be this one page,");
  x.push("     five hundred times over. `?` is a distinct URL to a crawler and the");
  x.push("     same record to the box — nukernel/ui/eight.js `readLink()` reads the");
  x.push("     search string when the fragment is empty and rewrites the address to");
  x.push("     the fragment form on landing, so the link a PERSON shares is still");
  x.push("     the one shape this app writes.");
  x.push("");
  x.push("     " + (Object.keys(FEED.GENRES).length - rows.length) + " rows are deliberately absent — " + FEED.UNLINKABLE.join(", ") + ".");
  x.push("     They are the box's own utility rows and carry a plain name instead of a");
  x.push("     \"Place Year\" label, so there is no (place, year) that names them and no");
  x.push("     honest link to offer. nukernel/atlas.js EXCLUDEs the same ten. -->");
  x.push('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');
  x.push("");
  x.push("  <url>");
  x.push("    <loc>" + SITE + "/</loc>");
  x.push("    <changefreq>weekly</changefreq>");
  x.push("    <priority>1.0</priority>");
  x.push("  </url>");
  x.push("");
  x.push("  <!-- the records, in the catalogue's own order -->");
  for (const r of rows) {
    x.push("  <url>");
    x.push("    <loc>" + esc(r.url) + "</loc>");   // &amp; — a raw & is invalid here
    x.push("    <changefreq>monthly</changefreq>");
    x.push("    <priority>0.6</priority>");
    x.push("  </url>");
  }
  x.push("");
  x.push("</urlset>");
  x.push("");
  return { xml: x.join("\n"), rows };
}

/* THE SELF-CHECK. No dependencies, so the sitemap validates itself: balanced
   tags, one <loc> per <url>, no raw ampersand outside a comment, every loc an
   absolute https URL under this site, and no duplicates. */
function check(xml, rows) {
  const errs = [];
  if (!/^<\?xml version="1\.0" encoding="UTF-8"\?>/.test(xml)) errs.push("missing XML declaration");
  const masked = xml.replace(/<!--[\s\S]*?-->/g, "");
  const urls = (masked.match(/<url>/g) || []).length;
  const locs = masked.match(/<loc>([^<]*)<\/loc>/g) || [];
  if (urls !== locs.length) errs.push(`url/loc mismatch (${urls}/${locs.length})`);
  if (urls !== rows.length + 1) errs.push(`expected ${rows.length + 1} <url>, found ${urls}`);
  const seen = new Set();
  for (const l of locs) {
    const u = l.slice(5, -6);
    if (!/^https:\/\/stellate\.app\//.test(u)) errs.push("loc is not an absolute site URL: " + u);
    if (/&(?!(amp|lt|gt|quot|apos);)/.test(u)) errs.push("loc has a raw ampersand: " + u);
    if (seen.has(u)) errs.push("duplicate loc: " + u);
    seen.add(u);
  }
  if (urls > 50000) errs.push("over the sitemap protocol's 50,000-URL limit — it needs an index");
  if (!/<\/urlset>/.test(xml)) errs.push("unclosed urlset");
  return errs;
}

function main() {
  const dry = process.argv.slice(2).includes("--dry");
  let built;
  try { built = build(); }
  catch (e) { console.error("gen-sitemap: " + e.message); process.exit(1); }
  const errs = check(built.xml, built.rows);
  if (errs.length) {
    for (const e of errs.slice(0, 6)) console.error("gen-sitemap: " + e);
    process.exit(1);
  }
  if (!dry) fs.writeFileSync(OUT, built.xml);
  const bytes = Buffer.byteLength(built.xml);
  console.log(`${dry ? "would write" : "wrote"} nukernel/sitemap.xml — 1 root + ${built.rows.length} records ` +
    `(${FEED.UNLINKABLE.length} rows skipped: no place/year label), ${bytes}B, ` +
    `first ${built.rows[0].label}, last ${built.rows[built.rows.length - 1].label}`);
}

module.exports = { build, check };
if (require.main === module) main();
