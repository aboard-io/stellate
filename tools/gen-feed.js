function main() {
  const argv = process.argv.slice(2);
  const flag = (n) => argv.includes(n);
  const val = (n, d) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
  const historic = flag("--historic");
  const dry = flag("--dry");
  const outDir = path.resolve(ROOT, val("--out", "."));
  const limit = parseInt(val("--limit", String(LIVE_MAX)), 10) || LIVE_MAX;
  const show = parseInt(val("--show", "0"), 10) || 0;

  if (flag("--sitemap")) { retuneSitemap(path.join(ROOT, "sitemap.xml"), dry); return; }

  const commits = readCommits();
  const releases = commits.filter((c) => !CHORE.some((re) => re.test(c.subject)))
    .filter((c) => !(/^(docs?|readme)\b/i.test(c.subject) && c.files.length && c.files.every((f) => /\.md$/i.test(f))))
    .filter((c) => !(!c.body.replace(/^(co-authored-by|claude-session).*$/gim, "").trim() && PLUMBING.test(c.subject)));
  const items = releases.map(entry);
  const live = items.slice(0, limit);

  if (show) {
    for (const it of items.slice(0, show)) {
      console.log("\n" + "═".repeat(78));
      console.log(new Date(it.c.date).toISOString().slice(0, 10) + "  " + it.c.subject);
      console.log("─".repeat(78));
      console.log(it.text);
    }
    console.log(`\n(${items.length} releases from ${commits.length} commits; ${commits.length - releases.length} skipped as chores)`);
    return;
  }

  const files = [];
  const liveMeta = {
    self: `${SITE}/feed.xml`, next: historic ? `${SITE}/feed-archive.xml` : null,
    title: "STELLATE — release notes",
    desc: `What shipped in STELLATE, the generative genre-space instrument by ${AUTHOR.name} (Aboard). Each entry links to a mix that plays what changed. Source: ${REPO} · colophon: ${SITE}/colophon.html`,
  };
  files.push(["feed.xml", rss(live, liveMeta)]);
  files.push(["feed.json", jsonfeed(live, { ...liveMeta, self: `${SITE}/feed.json`, next: historic ? `${SITE}/feed-archive.json` : null })]);
  if (historic) {
    const archMeta = {
      self: `${SITE}/feed-archive.xml`, next: null,
      title: "STELLATE — the complete release archive",
      desc: `Every release note in STELLATE's history, back to the first commit on ${new Date(items[items.length - 1].c.date).toISOString().slice(0, 10)}. The live feed (${SITE}/feed.xml) carries the most recent ${limit}.`,
    };
    files.push(["feed-archive.xml", rss(items, archMeta)]);
    files.push(["feed-archive.json", jsonfeed(items, { ...archMeta, self: `${SITE}/feed-archive.json` })]);
  }

  const reports = [];
  for (const [name, body] of files) {
    reports.push(name.endsWith(".xml") ? checkXml(body, name) : checkJson(body, name));
    if (!dry) fs.writeFileSync(path.join(outDir, name), body);
  }
  const bad = reports.filter((r) => r.errs.length);
  for (const r of reports) {
    const size = (files.find((f) => f[0] === r.label)[1].length / 1024).toFixed(1);
    console.log(`  ${dry ? "would write" : "wrote"} ${r.label.padEnd(18)} ${String(r.items).padStart(4)} items  ${size.padStart(7)} KB  ${r.errs.length ? "!! " + r.errs.join("; ") : "valid"}`);
  }
  console.log(`  ${items.length} releases from ${commits.length} commits (${commits.length - releases.length} chores skipped)`);
  if (bad.length) { console.error("gen-feed: invalid output — refusing to call this done"); process.exit(1); }
}

main();
