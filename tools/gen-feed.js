#!/usr/bin/env node
/* gen-feed.js — THE RELEASE FEED: shipped work, in the project's own voice,
   with a PLAYABLE link on every item.
   ==========================================================================
   The brief: the RSS is an automatically generated summary of new features in
   the code, generated by the deploy process, each item linking to a path that
   showcases the system.

   So this is not a commit firehose. The history is already written in themed
   batches — a subject line that reads like a headline, a body of ALL-CAPS
   sections and a closing gate wall — so the generator's whole job is to
   RE-READ that structure and lay it out as release notes:

     headline   = the commit subject (already a headline)
     lede       = the body's opening prose, unwrapped, first sentences
     highlights = the body's ALL-CAPS sections / bullets, one line each
     verified   = the "Gates:" / "Verified:" line, because the thesis of this
                  project is that a change lands only when the gates stay green
     ▶ play     = a URL INTO THE INSTRUMENT that shows off what changed

   THE PLAYABLE LINK (the interesting part). Every item links to a real mix:

     1. genres NAMED in the commit (ids, display labels, or genre-specs/*.json
        filenames) win. One genre → a tight loop parked on that star; two →
        a shuttle between them so you hear the blend; three or more → a
        constellation path that travels all three.
     2. otherwise the commit's TOPIC picks the genre that best exposes the
        change — found-sound work links a bed-heavy genre, harmony work links
        the jazziest one, drum work links the breakbeat one, master-EQ work
        links the mall-bright one (see THEMES below, each with the sentence
        that says WHY that genre).
     3. accessibility work links access.html, embed work links embed.html,
        explainer work links how.html — the surface that IS the feature.

   Waypoints come from the star map's own baked coordinates (app/world.js POS),
   so the links are real positions in the shipped space, not invented ones; the
   `xdur` speed multiple is solved per path so every showcase loop takes about
   half an hour whatever its size (share.js: ×1 is 1.2 s per world-unit, so a
   map-spanning triangle would otherwise take thirteen hours).

   USAGE
     node tools/gen-feed.js                 # feed.xml + feed.json (latest 50)
     node tools/gen-feed.js --historic      # …plus feed-archive.{xml,json}: everything
     node tools/gen-feed.js --limit 25      # a shorter live feed
     node tools/gen-feed.js --dry           # print what it would write, write nothing
     node tools/gen-feed.js --show 10       # dump 10 rendered entries as text (editing aid)
     node tools/gen-feed.js --sitemap       # re-solve sitemap.xml's deep genre links
                                            #   against the current app/world.js POS

   OUTPUT + THE ONE RULE. The feeds are DERIVED (git log is the source), so
   they are gitignored like every other derived artifact and regenerated on the
   way out the door: tools/deploy-stellate.sh runs `--historic` immediately
   before the rsync, which is also why the live feed can carry the commit that
   is being deployed. Nothing here is committed except this recipe.

   Zero dependencies: node + git. */

