// POS lives in app/world.js as an ES-module export; this tool is CommonJS and
// world.js is browser code, so read the literal rather than import the module.
const POS = (() => {
  const src = fs.readFileSync(path.join(ROOT, "app", "world.js"), "utf8");
  const i = src.indexOf("export const POS=");
  if (i < 0) throw new Error("gen-feed: app/world.js has no `export const POS=` — the map moved");
  // walk to the matching close brace of the object literal
  const open = src.indexOf("{", i);
  let depth = 0, end = -1;
  for (let j = open; j < src.length; j++) {
    if (src[j] === "{") depth++;
    else if (src[j] === "}") { depth--; if (!depth) { end = j; break; } }
  }
  const lit = src.slice(open, end + 1);
  // eslint-disable-next-line no-new-func
  return new Function("return (" + lit + ")")();
})();

