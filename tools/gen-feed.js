// 1. READ THE LOG
// ══════════════════════════════════════════════════════════════════════════
const US = "\x1f", RS = "\x1e";
function readCommits() {
  const out = execFileSync("git", ["-C", ROOT, "log", "--no-merges", "--date=iso-strict", "--name-only",
    `--format=${RS}%H${US}%aI${US}%an${US}%s${US}%b${US}`], { encoding: "utf8", maxBuffer: 1 << 28 });
  return out.split(RS).slice(1).map((chunk) => {
    const f = chunk.split(US);
    const files = (f[5] || "").split("\n").map((s) => s.trim()).filter(Boolean);
    return { sha: f[0].trim(), date: f[1], author: f[2], subject: (f[3] || "").trim(), body: f[4] || "", files };
  }).filter((c) => c.sha && c.subject);
}

// ══════════════════════════════════════════════════════════════════════════
// 2. READ A COMMIT MESSAGE AS RELEASE NOTES
// ══════════════════════════════════════════════════════════════════════════
const TRAILER = /^(co-authored-by|claude-session|signed-off-by|change-id|reviewed-by|🤖)/i;
const NOISE = [
  /\bsw\.js\s*(->|→|to)\s*v\d+\.?/gi, /\bsw v\d+\.?/gi,   // service-worker bumps
  /\s*\(local commits?[^)]*\)/gi,
];

function unwrap(lines) { return lines.join(" ").replace(/\s+/g, " ").trim(); }

// body → blocks; a block is {label, text} or {bullets:[…]}
function blocksOf(body) {
  const lines = body.split("\n").filter((l) => !TRAILER.test(l.trim()));
  const paras = lines.join("\n").split(/\n\s*\n/).map((p) => p.replace(/\s+$/, "")).filter((p) => p.trim());
  const out = [];
  for (const p of paras) {
    const ls = p.split("\n");
    if (ls.some((l) => /^\s*[-*•]\s+/.test(l))) {
      // a bullet block: fold continuation lines into their bullet
      const items = [];
      for (const l of ls) {
        if (/^\s*[-*•]\s+/.test(l)) items.push([l.replace(/^\s*[-*•]\s+/, "")]);
        else if (items.length) items[items.length - 1].push(l.trim());
        else items.push([l.trim()]);
      }
      for (const it of items) out.push(labelled(unwrap(it)));
      continue;
    }
    out.push(labelled(unwrap(ls)));
  }
  return out.filter((b) => b.text);
}
// "NAROPA (tools/fetch…): the readings…" → {label:"NAROPA", text:"the readings…"}
function labelled(text) {
  const m = /^([A-Z][A-Z0-9'’\/&+.\- ]{1,40}?)(\s*\([^)]{0,220}\))?\s*:\s+(.*)$/.exec(text);
  if (m && /[A-Z]{2,}/.test(m[1])) return { label: m[1].trim().replace(/\s+/g, " "), text: clean(m[3]) };
  return { label: "", text: clean(text) };
}
function clean(s) {
  let t = s;
  for (const re of NOISE) t = t.replace(re, "");
  // tidy spacing, but never close the gap in "the .csd" — a leading-dot
  // filename is not a stray space before a full stop
  return t.replace(/\s+/g, " ").replace(/\s+([,;])(?=\s|$)/g, "$1").replace(/\s+\.(?=\s|$)/g, ".").trim();
}
const GATEY = /^(gates?|gate wall|verified|verification|verify|tests?|test updates|proof|matrix|receipts)\b/i;
function isGate(b) { return GATEY.test(b.label || b.text); }

// clip to n chars on a sentence boundary where possible — a summary that ends
// mid-clause reads like a truncation error, which is exactly the changelog
// sludge this generator exists to avoid.
function clip(s, n) {
  if (s.length <= n) return s;
  const head = s.slice(0, n + 1);
  const stop = Math.max(head.lastIndexOf(". "), head.lastIndexOf("; "), head.lastIndexOf(" — "), head.lastIndexOf("! "), head.lastIndexOf("? "));
  if (stop > n * 0.45) return s.slice(0, stop + 1).replace(/[;,]$/, "").trim();
  const sp = head.lastIndexOf(" ");
  return (sp > 0 ? s.slice(0, sp) : s.slice(0, n)).replace(/[,;:—-]$/, "").trim() + "…";
}
// first 1–2 sentences, up to n chars
function sentences(s, n) {
  const parts = s.split(/(?<=[.!?])\s+(?=[A-Z(“"'])/);
  let out = parts[0] || s;
  if (out.length < n * 0.55 && parts[1]) out += " " + parts[1];
  return clip(out, n);
}

function summarize(c) {
  const bs = blocksOf(c.body);
  const gates = bs.filter(isGate);
  const rest = bs.filter((b) => !isGate(b));
  let lede = "", start = 0;
  if (rest.length && !rest[0].label) { lede = sentences(rest[0].text, 300); start = 1; }
  const highlights = [];
  for (const b of rest.slice(start)) {
    if (highlights.length >= 4) break;
    if (b.text.length < 18) continue;
    if (/:$/.test(b.text)) continue;   // a heading whose sub-list is elsewhere — nothing to say alone
    highlights.push({ label: b.label, text: clip(sentences(b.text, 210), 210) });
  }
  // a labelled-only body still deserves a lede: promote the first highlight
  if (!lede && highlights.length) lede = "";
  let verified = "";
  if (gates.length) {
    // the entry prints its own "Verified:" label, so drop the message's
    const g = gates.map((b) => b.text).join(" ")
      .replace(/^(gates?|gate wall|verified|verification|tests?|test updates|proof|receipts)\b[^A-Za-z0-9(]*/i, "")
      .replace(/^[—-]\s*/, "");
    verified = clip(g, 190);
  }
  return { lede, highlights, verified };
}

// ══════════════════════════════════════════════════════════════════════════
// 3. THE PLAYABLE LINK
// ══════════════════════════════════════════════════════════════════════════
// seed from the sha: deterministic, stable forever, 1..9999 (the app's range)
function seedOf(sha) { return (parseInt(sha.slice(0, 8), 16) % 9000) + 1000; }

function namedGenres(c) {
  const hay = (c.subject + "\n" + c.body).toLowerCase();
  const genreish = c.files.some((f) => GENRE_FILES.test(f));
  const hits = new Map();
  const bump = (id, n) => hits.set(id, (hits.get(id) || 0) + n);
  // strongest signal: a genre spec file in the diff
  for (const f of c.files) {
    const m = /^genre-specs\/([a-z0-9_-]+)\.json$/.exec(f);
    if (m && GENRES[m[1]]) bump(m[1], 50);
  }
  for (const id of IDS) {
    if (id.length < 4) continue;
    if (AMBIG.has(id) && !genreish) continue;
    // underscores are word characters here: `bbc_electro_gong` is a sample id,
    // not a mention of the electro genre (a real false positive)
    const re = new RegExp("(?:^|[^a-z0-9_])" + id + "(?:[^a-z0-9_]|$)", "g");
    const n = (hay.match(re) || []).length;
    if (n) bump(id, n);
    const lab = LABEL(id);
    if (lab && lab.length >= 9 && hay.includes(lab.toLowerCase())) bump(id, 3);
  }
  return [...hits.entries()].filter(([id]) => POS[id]).sort((a, b) => b[1] - a[1]).map(([id]) => id);
}

function themeOf(c) {
  const hay = c.subject + "\n" + c.body + "\n" + c.files.join("\n");
  for (const th of THEMES) if (th.re.test(hay)) return th;
  return null;
}

// nearest stars to a genre, for the "parked on this star" constellation
function neighbours(id, n) {
  const [x, y] = POS[id];
  return Object.keys(POS).filter((g) => g !== id)
    .map((g) => ({ g, d: Math.hypot(POS[g][0] - x, POS[g][1] - y) }))
    .sort((a, b) => a.d - b.d).slice(0, n);
}
const wp = (x, y) => Math.round(x) + "." + Math.round(y);
function perimeter(pts) {
  let p = 0;
  for (let i = 0; i < pts.length; i++) { const a = pts[i], b = pts[(i + 1) % pts.length]; p += Math.hypot(b[0] - a[0], b[1] - a[1]); }
  return p;
}
// share.js: at ×1 the loop takes 1.2 s per world-unit of perimeter. Solve the
// multiple so every showcase loop lands near half an hour whatever its size.
function speedMult(pts, targetSec = 1800) {
  const base = Math.max(30, perimeter(pts) * 1.2);
  const m = targetSec / base;
  if (m > 0.95 && m < 1.05) return null;
  return Math.round(Math.max(0.01, Math.min(1e6, m)) * 1000) / 1000;
}

// A single genre: a tight triangle ON the star. Radius 22 world-units keeps
// every point unambiguously nearest this anchor (the closest star pair in the
// baked layout is ~107 apart, and targeting.js snaps to the nearest anchor
// when the gap clears SNAP=64), so the loop plays the pure genre while the
// traveler still moves.
function orbit(id) {
  const [x, y] = POS[id], r = 22;
  return [0, 2.0944, 4.1888].map((a) => [x + r * Math.cos(a - Math.PI / 2), y + r * Math.sin(a - Math.PI / 2)]);
}

function showcase(c) {
  const seed = seedOf(c.sha);
  const named = namedGenres(c);
  const th = themeOf(c);
  let ids, where, page = "";
  if (named.length >= 3) { ids = named.slice(0, 3); where = "the three genres this change names, as one path"; }
  else if (named.length === 2) { ids = named.slice(0, 2); where = "a shuttle between the two genres this change names — the blend is the point"; }
  else if (named.length === 1) { ids = named.slice(0, 1); where = "parked on the genre this change names"; }
  else if (th) { ids = th.genres.slice(); where = th.where; page = th.page || ""; }
  else { ids = DEFAULT_PATH.slice(); where = DEFAULT_WHERE; }
  // a NAMED genre always wins over a theme's alternate surface: if the commit
  // says "budstep", the link plays budstep on the map, not access.html.
  ids = ids.filter((id) => POS[id]);
  if (!ids.length) ids = DEFAULT_PATH.slice();

  // a page-specific surface (access/embed/how) IS the showcase
  if (page === "how.html") return { url: `${SITE}/how.html`, ids: [], where, label: "read how a song is made" };
  const q = new URLSearchParams();
  q.set("genre", ids[0]);
  q.set("seed", String(seed));
  let pts;
  if (ids.length === 1) pts = orbit(ids[0]);
  else pts = ids.map((id) => [POS[id][0], POS[id][1]]);
  if (page === "access.html") {
    // the accessible page takes a genre + seed directly; no map, no path
    return { url: `${SITE}/access.html?genre=${ids[0]}&seed=${seed}`, ids: [ids[0]], where, label: LABEL(ids[0]) };
  }
  q.set("path", pts.map((p) => wp(p[0], p[1])).join(","));
  const m = speedMult(pts);
  if (m) q.set("xdur", String(m));
  const base = page === "embed.html" ? `${SITE}/embed.html` : `${SITE}/`;
  return { url: base + "?" + q.toString().replace(/%2C/g, ","), ids, where, label: ids.map(LABEL).join(" → ") };
}

// ══════════════════════════════════════════════════════════════════════════
// 4. RENDER
// ══════════════════════════════════════════════════════════════════════════
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const cdata = (s) => "<![CDATA[" + String(s).replace(/\]\]>/g, "]]&gt;") + "]]>";

function entry(c) {
  const s = summarize(c);
  const show = showcase(c);
  const commitUrl = `${REPO}/commit/${c.sha}`;
  const short = c.sha.slice(0, 7);
  const playText = show.ids.length
    ? `▶ Play it: ${show.label} — ${show.where}`
    : `▶ ${show.label} — ${show.where}`;

  const html = [];
  if (s.lede) html.push(`<p>${esc(s.lede)}</p>`);
  if (s.highlights.length) {
    html.push("<ul>" + s.highlights.map((h) =>
      `<li>${h.label ? `<strong>${esc(h.label)}</strong> — ` : ""}${esc(h.text)}</li>`).join("") + "</ul>");
  }
  if (s.verified) html.push(`<p><em>Verified:</em> ${esc(s.verified)}</p>`);
  html.push(`<p><a href="${esc(show.url)}">${esc(playText)}</a></p>`);
  html.push(`<p><small><a href="${esc(commitUrl)}">${short}</a> · <a href="${SITE}/colophon.html">colophon</a> · <a href="${REPO}">source</a></small></p>`);

  const text = [
    s.lede,
    ...s.highlights.map((h) => (h.label ? h.label + " — " : "• ") + h.text),
    s.verified ? "Verified: " + s.verified : "",
    playText + " " + show.url,
    short + " " + commitUrl,
  ].filter(Boolean).join("\n\n");

  const tags = [...new Set([...show.ids, ...(themeOf(c) ? [themeOf(c).t] : [])])];
  return { c, s, show, commitUrl, short, html: html.join("\n"), text, tags,
    summary: s.lede || (s.highlights[0] ? (s.highlights[0].label ? s.highlights[0].label + " — " : "") + s.highlights[0].text : c.subject) };
}

function rss(items, { self, title, desc, next }) {
  const now = new Date().toUTCString();
  const x = [];
  x.push('<?xml version="1.0" encoding="UTF-8"?>');
  x.push('<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:dc="http://purl.org/dc/elements/1.1/">');
  x.push("<channel>");
  x.push(`<title>${esc(title)}</title>`);
  x.push(`<link>${SITE}/</link>`);
  x.push(`<description>${esc(desc)}</description>`);
  x.push("<language>en-us</language>");
  x.push(`<managingEditor>${AUTHOR.email} (${AUTHOR.name})</managingEditor>`);
  x.push(`<webMaster>${AUTHOR.email} (${AUTHOR.name})</webMaster>`);
  x.push(`<copyright>MIT — © 2026 ${esc(AUTHOR.name)}. Source: ${REPO}</copyright>`);
  x.push(`<lastBuildDate>${now}</lastBuildDate>`);
  if (items[0]) x.push(`<pubDate>${new Date(items[0].c.date).toUTCString()}</pubDate>`);
  x.push("<generator>tools/gen-feed.js (stellate) — release notes from the git log</generator>");
  x.push("<docs>https://www.rssboard.org/rss-specification</docs>");
  x.push("<ttl>1440</ttl>");
  x.push("<category>Music</category><category>Generative art</category><category>Open source</category>");
  x.push(`<image><url>${SITE}/assets/icon-180.png</url><title>${esc(title)}</title><link>${SITE}/</link><width>144</width><height>144</height></image>`);
  x.push(`<atom:link rel="self" href="${esc(self)}" type="application/rss+xml"/>`);
  if (next) x.push(`<atom:link rel="next" href="${esc(next)}" type="application/rss+xml"/>`);
  x.push(`<atom:link rel="alternate" href="${SITE}/colophon.html" type="text/html" title="Colophon — how STELLATE is made and what it is made of"/>`);
  x.push(`<atom:link rel="related" href="${REPO}" type="text/html" title="Source on GitHub"/>`);
  for (const it of items) {
    x.push("<item>");
    x.push(`<title>${esc(it.c.subject)}</title>`);
    x.push(`<link>${esc(it.show.url)}</link>`);
    x.push(`<guid isPermaLink="false">${it.c.sha}</guid>`);
    x.push(`<pubDate>${new Date(it.c.date).toUTCString()}</pubDate>`);
    x.push(`<dc:creator>${esc(AUTHOR.name)}</dc:creator>`);
    x.push(`<author>${AUTHOR.email} (${esc(AUTHOR.name)})</author>`);
    for (const t of it.tags) x.push(`<category>${esc(t)}</category>`);
    x.push(`<description>${cdata(it.summary)}</description>`);
    x.push(`<content:encoded>${cdata(it.html)}</content:encoded>`);
    x.push(`<comments>${esc(it.commitUrl)}</comments>`);
    x.push("</item>");
  }
  x.push("</channel>", "</rss>", "");
  return x.join("\n");
}

