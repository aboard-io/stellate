// 4b. THE SITEMAP'S DEEP LINKS
// ══════════════════════════════════════════════════════════════════════════
// sitemap.xml is committed (a crawler must find it in a clean clone), but its
// genre URLs carry BAKED star coordinates, and app/world.js POS gets re-baked
// whenever the catalog grows. `--sitemap` re-solves every one of those URLs
// against the current map, keeping each entry's seed so the music is stable.
// test/feed-links-run.js fails when they drift, which is how you find out.
function genreUrl(id, seed) {
  const pts = orbit(id);
  const q = new URLSearchParams();
  q.set("genre", id); q.set("seed", String(seed));
  q.set("path", pts.map((p) => wp(p[0], p[1])).join(","));
  const m = speedMult(pts);
  if (m) q.set("xdur", String(m));
  // literal commas: legal in a query string and far kinder to read in a
  // sitemap or a feed reader than %2C
  return SITE + "/?" + q.toString().replace(/%2C/g, ",");
}
function retuneSitemap(file, dry) {
  const src = fs.readFileSync(file, "utf8");
  let n = 0;
  const out = src.replace(/https:\/\/stellate\.app\/\?genre=([a-z0-9_-]+)&amp;seed=(\d+)[^<]*/g, (m0, id, seed) => {
    if (!POS[id]) { console.error(`  !! sitemap names a genre with no star: ${id}`); return m0; }
    const url = genreUrl(id, +seed).replace(/&/g, "&amp;");
    if (url !== m0) n++;
    return url;
  });
  if (!dry && n) fs.writeFileSync(file, out);
  console.log(`  ${dry ? "would retune" : "retuned"} sitemap.xml: ${n} deep link${n === 1 ? "" : "s"} re-solved against the current map`);
  return n;
}

