#!/usr/bin/env node
/* tools/video-manifest.js — THE PUBLIC-DOMAIN VIDEO CRATE, LISTED.
 *
 * Paul, 2026-09-01: "add a major icon and section: Video. Use the prior work we
 * did on screensavers and archive.org video clips ... Make sure you find the
 * work first before start it, we had a whole system for automatically splicing
 * video clips."
 *
 * THE PRIOR WORK IS REAL AND IT IS DOCUMENTED IN SOURCES.md, which is where I
 * looked before writing a line. `video-layer.js` streamed short cue windows out
 * of archive.org against a committed `stream-catalog.json` of {item, file, in,
 * out} + genre tags; `fetch-found-video.sh` / `cut-lib-clips.sh` baked the same
 * windows to small silent MP4s in `found/video/` as an offline fallback. The
 * layer was REMOVED and the attribution ledger deliberately kept.
 *
 * WHAT IT LISTS, AND WHOSE DECISION THAT IS. This shipped first taking the
 * `av_` prefix alone — the 1920s-30s abstract film SOURCES.md records as PD by
 * age and CC Public Domain Mark 1.0 (Ruttmann, Eggeling, Moholy-Nagy, Ballet
 * Mecanique) — because the same ledger is blunt that the rest is tier-2 and
 * tier-3: "none stated" licences on LaserDisc rips, "precisely the tier-3 case
 * where no licence chain exists to comply with".
 *
 * Paul, 2026-09-01: "Serve everything. I take responsibility for copyright."
 * It is his project, his server and his material, and that is his call to make
 * as the operator. So the filter is gone and all 240 local clips are listed.
 * The tiering is NOT deleted from SOURCES.md and this comment does not soften
 * it: the ledger is what makes a rights holder answerable-to, and it now
 * records both the wider serving and whose decision it was. An attribution
 * ledger that shrinks when the policy changes is not a ledger — the file says
 * so itself, and it was right.
 *
 * Run: node tools/video-manifest.js   (writes nukernel/ui/video-clips.js)
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "found/video");
const OUT = path.join(ROOT, "nukernel/ui/video-clips.js");

const dur = (f) => {
  try {
    return +execFileSync("ffprobe", ["-v", "quiet", "-show_entries", "format=duration",
      "-of", "csv=p=0", f], { encoding: "utf8" }).trim() || 0;
  } catch { return 0; }
};

const files = readdirSync(DIR).filter((f) => /\.mp4$/.test(f)).sort();
const rows = files.map((f) => {
  const p = path.join(DIR, f);
  return { f, s: statSync(p).size, d: +dur(p).toFixed(2) };
});
const total = rows.reduce((a, r) => a + r.s, 0);

writeFileSync(OUT, `// nukernel/ui/video-clips.js — GENERATED BY tools/video-manifest.js — DO NOT EDIT.
//
// found/video: ${rows.length} clips, ${(total / 1048576).toFixed(1)} MB.
// The \`av_\` rows are PD by age (1921) / CC Public Domain Mark 1.0 — Ruttmann,
// Eggeling, Moholy-Nagy, Ballet Mecanique. The rest are the tier-2/tier-3
// LaserDisc material SOURCES.md tiers and attributes; it is served on Paul's
// explicit decision of 2026-09-01 ("Serve everything. I take responsibility for
// copyright"), and the ledger records both the material and the decision.
//
// ROOT-RELATIVE ON PURPOSE. The crate lives at the SITE root (/found/video/),
// and nukernel is served from the root on staging but from /nukernel/ in a
// local tree — a bare "found/video/" resolved to /nukernel/found/video/ and
// 404'd, which the browser test caught before this shipped. Nothing is fetched
// off-origin either way.
export const VIDEO_DIR = "/found/video/";
export const CLIPS = ${JSON.stringify(rows, null, 0).replace(/},/g, "},\n  ").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`);
console.log("wrote " + path.relative(ROOT, OUT) + " — " + rows.length + " clips, " +
            (total / 1048576).toFixed(1) + " MB");
