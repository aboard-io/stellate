#!/usr/bin/env node
/* tools/video-manifest.js — THE PUBLIC-DOMAIN VIDEO CRATE, LISTED.
 *
 * Paul, 2026-09-01: "add a major icon and section: Video. Use the prior work we
 * did on screensavers and archive.org video clips ... Make sure you find the
 * work first before start it, we had a whole system for automatically splicing
 * video clips."
 *
 * THE PRIOR WORK IS REAL AND IT IS DOCUMENTED IN SOURCES.md, which is where I
 * looked before writing a line. `video-layer.js` streamed short cue windows out
 * of archive.org against a committed `stream-catalog.json` of {item, file, in,
 * out} + genre tags; `fetch-found-video.sh` / `cut-lib-clips.sh` baked the same
 * windows to small silent MP4s in `found/video/` as an offline fallback. The
 * layer was REMOVED and the attribution ledger deliberately kept.
 *
 * AND THE LEDGER IS WHY THIS SCRIPT ONLY TAKES ONE PREFIX. SOURCES.md is blunt
 * about the removed material: most of it is tier-2/tier-3, "none stated"
 * licences on LaserDisc rips, "precisely the tier-3 case where no licence chain
 * exists to comply with". Those clips stay out. What this lists is the `av_`
 * tier ONLY — the 1920s-30s abstract film the same ledger records as PD BY AGE
 * and CC Public Domain Mark 1.0: Ruttmann's Opus I (1921), Eggeling's
 * Symphonie Diagonale (1921), Moholy-Nagy, Ballet Mecanique. That is 97 of the
 * 242 local clips, and it is the half a project can serve.
 *
 * Run: node tools/video-manifest.js   (writes nukernel/ui/video-clips.js)
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "found/video");
const OUT = path.join(ROOT, "nukernel/ui/video-clips.js");

const dur = (f) => {
  try {
    return +execFileSync("ffprobe", ["-v", "quiet", "-show_entries", "format=duration",
      "-of", "csv=p=0", f], { encoding: "utf8" }).trim() || 0;
  } catch { return 0; }
};

const files = readdirSync(DIR).filter((f) => /^av_.*\.mp4$/.test(f)).sort();
const rows = files.map((f) => {
  const p = path.join(DIR, f);
  return { f, s: statSync(p).size, d: +dur(p).toFixed(2) };
});
const total = rows.reduce((a, r) => a + r.s, 0);

writeFileSync(OUT, `// nukernel/ui/video-clips.js — GENERATED BY tools/video-manifest.js — DO NOT EDIT.
//
// The PUBLIC-DOMAIN half of found/video: ${rows.length} clips, ${(total / 1048576).toFixed(1)} MB.
// Prefix \`av_\` only. SOURCES.md records these as PD by age (1921) and CC
// Public Domain Mark 1.0 — Ruttmann, Eggeling, Moholy-Nagy, Ballet Mecanique.
// The tier-2/tier-3 LaserDisc material in that folder is NOT listed and is not
// served; see the ledger's own note on why it was withdrawn.
//
// ROOT-RELATIVE ON PURPOSE. The crate lives at the SITE root (/found/video/),
// and nukernel is served from the root on staging but from /nukernel/ in a
// local tree — a bare "found/video/" resolved to /nukernel/found/video/ and
// 404'd, which the browser test caught before this shipped. Nothing is fetched
// off-origin either way.
export const VIDEO_DIR = "/found/video/";
export const CLIPS = ${JSON.stringify(rows, null, 0).replace(/},/g, "},\n  ").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`);
console.log("wrote " + path.relative(ROOT, OUT) + " — " + rows.length + " clips, " +
            (total / 1048576).toFixed(1) + " MB");
